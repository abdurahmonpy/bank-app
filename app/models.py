from decimal import Decimal
from django.db import models
from app.utils import format_card, card_mask, format_phone, phone_mask


class CardStatus(models.TextChoices):
    ACTIVE = "active", "Active"
    INACTIVE = "inactive", "Inactive"
    EXPIRED = "expired", "Expired"


class Card(models.Model):
    card_number = models.CharField(
        max_length=20,
        unique=True,
        db_index=True,
        help_text="16-digit normalized card number (e.g. 8600123456789012)",
    )
    expire = models.CharField(
        max_length=10,
        help_text="Expiry date in MM/YY format",
    )
    phone = models.CharField(
        max_length=25,
        blank=True,
        null=True,
        help_text="Cardholder phone number",
    )
    status = models.CharField(
        max_length=10,
        choices=CardStatus.choices,
        default=CardStatus.ACTIVE,
        db_index=True,
    )
    balance = models.DecimalField(
        max_digits=15,
        decimal_places=2,
        default=Decimal("0.00"),
        help_text="Card balance in UZS (between 0 and 1,200,000,000)",
    )
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = "cards"
        ordering = ["-created_at"]
        verbose_name = "Bank Card"
        verbose_name_plural = "Bank Cards"

    def __str__(self):
        return f"{self.masked_card} ({self.status}) - {self.balance:,.2f} UZS"

    @property
    def formatted_card(self):
        return format_card(self.card_number)

    @property
    def masked_card(self):
        return card_mask(self.card_number)

    @property
    def formatted_phone_display(self):
        return format_phone(self.phone) if self.phone else "-"

    @property
    def masked_phone(self):
        return phone_mask(self.phone) if self.phone else "-"


class TransferState(models.TextChoices):
    CREATED = "created", "Created"
    CONFIRMED = "confirmed", "Confirmed"
    CANCELLED = "cancelled", "Cancelled"


class Transfer(models.Model):
    ext_id = models.CharField(
        max_length=100,
        unique=True,
        db_index=True,
        help_text="Unique external transaction ID generated by client",
    )
    sender_card_number = models.CharField(max_length=20, db_index=True)
    receiver_card_number = models.CharField(max_length=20, db_index=True)
    sender_card_expiry = models.CharField(max_length=10)
    sender_phone = models.CharField(max_length=25, blank=True, null=True)
    receiver_phone = models.CharField(max_length=25, blank=True, null=True)
    sending_amount = models.DecimalField(max_digits=15, decimal_places=2)
    currency = models.CharField(
        max_length=10,
        default="860",
        help_text="Currency code: 860 (UZS), 643 (RUB), 840 (USD)",
    )
    receiving_amount = models.DecimalField(max_digits=15, decimal_places=2)
    state = models.CharField(
        max_length=15,
        choices=TransferState.choices,
        default=TransferState.CREATED,
        db_index=True,
    )
    try_count = models.IntegerField(default=0, help_text="OTP attempt count (max 3)")
    otp = models.CharField(max_length=10, blank=True, null=True, help_text="6-digit OTP code")

    created_at = models.DateTimeField(auto_now_add=True)
    confirmed_at = models.DateTimeField(blank=True, null=True)
    cancelled_at = models.DateTimeField(blank=True, null=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = "transfers"
        ordering = ["-created_at"]
        verbose_name = "Transfer"
        verbose_name_plural = "Transfers"

    def __str__(self):
        return f"Transfer {self.ext_id} [{self.state}] - {self.sending_amount} ({self.currency})"


class Error(models.Model):
    code = models.IntegerField(unique=True, db_index=True, help_text="Unique error code")
    en = models.CharField(max_length=255, help_text="Error message in English")
    ru = models.CharField(max_length=255, help_text="Error message in Russian")
    uz = models.CharField(max_length=255, help_text="Error message in Uzbek")

    class Meta:
        db_table = "errors"
        ordering = ["code"]
        verbose_name = "Error Message"
        verbose_name_plural = "Error Messages"

    def __str__(self):
        return f"[{self.code}] {self.en}"

    @classmethod
    def get_message(cls, code: int, lang: str = "en") -> str:
        """Helper to get localized message by code"""
        err = cls.objects.filter(code=code).first()
        if not err:
            return "Unknown error"
        lang_lower = lang.lower()
        if lang_lower == "uz":
            return err.uz
        elif lang_lower == "ru":
            return err.ru
        return err.en
